export function getKnowledgeForCase(practiceCase) {
  if (!practiceCase) return getDefaultKnowledge()
  const category = practiceCase.category
  if (category && caseKnowledgeMap[category]) {
    return caseKnowledgeMap[category]
  }
  // 按销售目标/现病史关键词模糊匹配
  const text = (practiceCase.销售目标 || '') + (practiceCase.现病史 || '')
  if (/血糖|糖尿病|胰岛素/.test(text)) return caseKnowledgeMap['高血糖']
  if (/血压/.test(text)) return caseKnowledgeMap['高血压']
  if (/血脂|胆固醇|甘油三酯/.test(text)) return caseKnowledgeMap['高血脂']
  if (/尿酸|痛风/.test(text)) return caseKnowledgeMap['高尿酸']
  if (/胃|消化|反酸|肠/.test(text)) return caseKnowledgeMap['消化内科']
  if (/中医|气虚|阴虚|血瘀/.test(text)) return caseKnowledgeMap['中医内科']
  return getDefaultKnowledge()
}

